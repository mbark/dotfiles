// ==================== macros ====================
// ä and ö are typed as Option+U followed by the letter, which assumes the
// macOS US layout. Option+U is only a dead key without Shift, so the held
// mods are dropped for it and restored for the letter.
static void tap_umlaut(uint8_t letter) {
    const uint8_t mods = get_mods();
    clear_mods();
    tap_code16(A(KC_U));
    set_mods(mods);
    tap_code(letter);
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    if (record->event.pressed) {
        switch (keycode) {
            case SWE_AA:
                tap_code16(A(KC_A));
                return false;
            case SWE_AE:
                tap_umlaut(KC_A);
                return false;
            case SWE_OE:
                tap_umlaut(KC_O);
                return false;
        }
    }
    return true;
}

// Runs constantly in the background, in a loop.
void matrix_scan_user(void) {
    uint8_t layer = biton32(layer_state);

    ergodox_board_led_off();
    ergodox_right_led_1_off();
    ergodox_right_led_2_off();
    ergodox_right_led_3_off();
    // The layer number in binary, led 1 being the lowest bit
    if (layer & 1) {
        ergodox_right_led_1_on();
    }
    if (layer & 2) {
        ergodox_right_led_2_on();
    }
    if (layer & 4) {
        ergodox_right_led_3_on();
    }
};

